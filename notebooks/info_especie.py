def resultado_fecha_vacia():
    """
    Devuelve un resultado vacío para una fecha no interpretable.
    """

    return pd.Series(
        [pd.NA, pd.NA, pd.NA],
        index=[
            "year_event",
            "month_event",
            "day_event",
        ],
    )


def fecha_valida(year, month, day):
    """
    Comprueba si una combinación de año, mes y día es válida.
    """

    try:
        pd.Timestamp(
            year=int(year),
            month=int(month),
            day=int(day),
        )

        return True

    except (TypeError, ValueError):
        return False


def extraer_fecha_event_date(valor):
    """
    Extrae year, month y day desde eventDate.

    Formatos contemplados:
        2020-07-15
        2020-07-15T10:30:00Z
        2020-07-15T10:30:00+02:00
        2020-07-15/2020-07-20
        2020-07
        2020
        2020/07/15
        15/07/2020
        15-07-2020

    En un intervalo se utiliza la fecha inicial.

    Si solo existe el año:
        year = año
        month = null
        day = null

    Si solo existen año y mes:
        year = año
        month = mes
        day = null
    """

    if valor is None:
        return resultado_fecha_vacia()

    try:
        if pd.isna(valor):
            return resultado_fecha_vacia()
    except (TypeError, ValueError):
        pass

    texto = str(valor).strip()

    if not texto:
        return resultado_fecha_vacia()

    columnas = [
        "year_event",
        "month_event",
        "day_event",
    ]

    # ----------------------------------------------------------
    # Formato YYYY-MM-DD o YYYY/MM/DD
    # ----------------------------------------------------------

    coincidencia = re.search(
        r"(?<!\d)"
        r"(\d{4})"
        r"[-/]"
        r"(\d{1,2})"
        r"[-/]"
        r"(\d{1,2})"
        r"(?!\d)",
        texto,
    )

    if coincidencia:
        year = int(coincidencia.group(1))
        month = int(coincidencia.group(2))
        day = int(coincidencia.group(3))

        if fecha_valida(
            year,
            month,
            day,
        ):
            return pd.Series(
                [year, month, day],
                index=columnas,
            )

    # ----------------------------------------------------------
    # Formato DD/MM/YYYY o DD-MM-YYYY
    # ----------------------------------------------------------

    coincidencia = re.search(
        r"(?<!\d)"
        r"(\d{1,2})"
        r"[-/]"
        r"(\d{1,2})"
        r"[-/]"
        r"(\d{4})"
        r"(?!\d)",
        texto,
    )

    if coincidencia:
        day = int(coincidencia.group(1))
        month = int(coincidencia.group(2))
        year = int(coincidencia.group(3))

        if fecha_valida(
            year,
            month,
            day,
        ):
            return pd.Series(
                [year, month, day],
                index=columnas,
            )

    # ----------------------------------------------------------
    # Formato parcial YYYY-MM o YYYY/MM
    # ----------------------------------------------------------

    coincidencia = re.search(
        r"(?<!\d)"
        r"(\d{4})"
        r"[-/]"
        r"(\d{1,2})"
        r"(?![-/\d])",
        texto,
    )

    if coincidencia:
        year = int(coincidencia.group(1))
        month = int(coincidencia.group(2))

        if (
            1800 <= year <= 2100
            and 1 <= month <= 12
        ):
            return pd.Series(
                [year, month, pd.NA],
                index=columnas,
            )

    # ----------------------------------------------------------
    # Formato que contiene únicamente el año
    # ----------------------------------------------------------

    coincidencia = re.search(
        r"(?<!\d)"
        r"(18\d{2}|19\d{2}|20\d{2}|2100)"
        r"(?!\d)",
        texto,
    )

    if coincidencia:
        year = int(
            coincidencia.group(1)
        )

        return pd.Series(
            [year, pd.NA, pd.NA],
            index=columnas,
        )

    # ----------------------------------------------------------
    # Intento adicional con pandas
    # ----------------------------------------------------------

    try:
        texto_parseable = texto

        # Si parece un intervalo ISO, usar su primera fecha.
        intervalo_iso = re.match(
            r"^\s*(\d{4}-\d{1,2}-\d{1,2})/",
            texto,
        )

        if intervalo_iso:
            texto_parseable = intervalo_iso.group(1)

        fecha = pd.to_datetime(
            texto_parseable,
            errors="coerce",
            utc=True,
        )

        if pd.notna(fecha):
            return pd.Series(
                [
                    int(fecha.year),
                    int(fecha.month),
                    int(fecha.day),
                ],
                index=columnas,
            )

    except Exception:
        pass

    return resultado_fecha_vacia()


