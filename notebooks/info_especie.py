# 6. CONSULTAR LA API DE OBIS
# ======================================================================

def consultar_obis(parametros, max_intentos=5):
    """
    Consulta OBIS con reintentos automaticos.
    """

    cabeceras = {
        "Accept": "application/json",
        "User-Agent": (
            "NASA-Space-Apps-Earth-Trend-Detective/1.0 "
            "(educational hackathon project)"
        ),
    }

    ultimo_error = None

    for intento in range(1, max_intentos + 1):
        try:
            respuesta = requests.get(
                URL_OBIS,
                params=parametros,
                headers=cabeceras,
                timeout=120,
            )

            # Estos errores suelen ser temporales.
            if (
                respuesta.status_code == 429
                or respuesta.status_code >= 500
            ):
                espera = min(
                    60,
                    2 ** intento,
                )

                print(
                    f"Error temporal {respuesta.status_code}. "
                    f"Reintentando en {espera} segundos..."
                )

                time.sleep(espera)
                continue

            respuesta.raise_for_status()

            return respuesta.json()

        except requests.RequestException as error:
            ultimo_error = error

            if intento < max_intentos:
                espera = min(
                    60,
                    2 ** intento,
                )

                print(
                    f"Problema de conexion: {error}\n"
                    f"Reintentando en {espera} segundos..."
                )

                time.sleep(espera)

    raise RuntimeError(
        "No se pudo obtener una respuesta valida de OBIS."
    ) from ultimo_error


