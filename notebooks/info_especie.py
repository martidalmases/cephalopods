def generar_nombre_archivo(especie):
    """
    Genera un nombre de archivo JSON seguro a partir de la especie.

    Ejemplos:
        Posidonia oceanica -> Posidonia_oceanica.json
        Caretta caretta    -> Caretta_caretta.json
        Thunnus thynnus    -> Thunnus_thynnus.json
    """

    nombre = str(especie).strip()

    if not nombre:
        raise ValueError(
            "ESPECIE no puede estar vacía."
        )

    # Convertir caracteres acentuados a caracteres ASCII.
    nombre = unicodedata.normalize(
        "NFKD",
        nombre,
    ).encode(
        "ascii",
        "ignore",
    ).decode("ascii")

    # Sustituir espacios por guiones bajos.
    nombre = re.sub(
        r"\s+",
        "_",
        nombre,
    )

    # Eliminar caracteres problemáticos para nombres de archivo.
    nombre = re.sub(
        r"[^A-Za-z0-9_-]",
        "",
        nombre,
    )

    # Evitar guiones bajos repetidos.
    nombre = re.sub(
        r"_+",
        "_",
        nombre,
    )

    nombre = nombre.strip("_-")

    if not nombre:
        raise ValueError(
            "No se pudo generar un nombre de archivo desde ESPECIE."
        )

    return f"{nombre}.json"


