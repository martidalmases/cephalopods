# Guardar primero en un archivo temporal evita dejar un JSON
# incompleto si la escritura se interrumpe.
RUTA_TEMPORAL = Path(
    str(RUTA_JSON) + ".tmp"
)

with open(
    RUTA_TEMPORAL,
    mode="w",
    encoding="utf-8",
) as archivo_json:
    json.dump(
        registros_json,
        archivo_json,
        ensure_ascii=False,
        indent=2,
        allow_nan=False,
    )

# Reemplazar el archivo anterior, si existe.
RUTA_TEMPORAL.replace(
    RUTA_JSON
)


# ======================================================================
# 23. COMPROBAR EL JSON GUARDADO
# ======================================================================

if not RUTA_JSON.exists():
    raise FileNotFoundError(
        f"No se ha creado el archivo:\n{RUTA_JSON}"
    )

with open(
    RUTA_JSON,
    mode="r",
    encoding="utf-8",
) as archivo_json:
    datos_comprobacion = json.load(
        archivo_json
    )

if not isinstance(
    datos_comprobacion,
    list,
):
    raise RuntimeError(
        "El archivo creado no contiene una lista JSON."
    )

if len(datos_comprobacion) != len(df_final):
    raise RuntimeError(
        "El número de registros del JSON no coincide "
        "con el número de observaciones procesadas."
    )

if datos_comprobacion:
    campos_guardados = list(
        datos_comprobacion[0].keys()
    )

    if campos_guardados != COLUMNAS_FINALES:
        raise RuntimeError(
            "El JSON no contiene exactamente los campos esperados.\n"
            f"Campos encontrados: {campos_guardados}"
        )

    if "day" in campos_guardados:
        raise RuntimeError(
            "El campo day continúa apareciendo en el JSON."
        )


# ======================================================================
# 24. CALCULAR EL RESUMEN
