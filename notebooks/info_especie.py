# 7. EXTRAER LOS REGISTROS DE LA RESPUESTA
# ======================================================================

def extraer_registros(respuesta_json):
    """
    Extrae la lista de observaciones de la respuesta de OBIS.
    """

    if isinstance(respuesta_json, list):
        return respuesta_json

    if not isinstance(respuesta_json, dict):
        raise ValueError(
            "OBIS ha devuelto un formato inesperado."
        )

    if isinstance(
        respuesta_json.get("results"),
        list,
    ):
        return respuesta_json["results"]

    if isinstance(
        respuesta_json.get("data"),
        list,
    ):
        return respuesta_json["data"]

    raise ValueError(
        "No se encontraron observaciones en la respuesta de OBIS. "
        f"Claves recibidas: {list(respuesta_json.keys())}"
    )


