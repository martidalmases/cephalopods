# 8. DESCARGAR LAS OBSERVACIONES
# ======================================================================

def descargar_observaciones(
    especie,
    tamano_lote=2000,
    max_registros=None,
):
    """
    Descarga observaciones desde OBIS utilizando paginacion
    mediante el cursor 'after'.

    Todos los registros recibidos se conservan, incluidos
    los registros duplicados.
    """

    registros_totales = []
    cursor_after = None
    numero_pagina = 1

    while True:
        tamano_peticion = tamano_lote

        if max_registros is not None:
            registros_restantes = (
                max_registros
                - len(registros_totales)
            )

            if registros_restantes <= 0:
                break

            tamano_peticion = min(
                tamano_lote,
                registros_restantes,
            )

        parametros = {
            "scientificname": especie,
            "size": tamano_peticion,
            "fields": ",".join(CAMPOS_OBIS),
        }

        if cursor_after is not None:
            parametros["after"] = cursor_after

        respuesta_json = consultar_obis(
            parametros
        )

        registros_pagina = extraer_registros(
            respuesta_json
        )

        if not registros_pagina:
            break

        # Se conservan todos los registros.
        registros_totales.extend(
            registros_pagina
        )

        print(
            f"Pagina {numero_pagina}: "
            f"{len(registros_pagina):,} registros | "
            f"Total acumulado: {len(registros_totales):,}"
        )

        if max_registros is not None:
            if len(registros_totales) >= max_registros:
                registros_totales = registros_totales[
                    :max_registros
                ]
                break

        # Si llegan menos registros de los solicitados,
        # hemos alcanzado la ultima pagina.
        if len(registros_pagina) < tamano_peticion:
            break

        ultimo_id = registros_pagina[-1].get(
            "id"
        )

        if ultimo_id is None:
            raise RuntimeError(
                "El ultimo registro no contiene 'id'. "
                "No se puede continuar la paginacion."
            )

        if ultimo_id == cursor_after:
            raise RuntimeError(
                "OBIS ha repetido el cursor. "
                "La descarga se detiene para evitar un bucle."
            )

        cursor_after = ultimo_id
        numero_pagina += 1

        # Pausa para no saturar la API.
        time.sleep(0.3)

    return pd.DataFrame(
        registros_totales
    )


