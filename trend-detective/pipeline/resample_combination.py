def convertir_url_github_a_raw(url):
    """
    Convierte una URL normal de GitHub en una URL RAW.
    """

    if "raw.githubusercontent.com" in url:
        return url

    if "github.com" in url and "/blob/" in url:

        url = url.replace(
            "https://github.com/",
            "https://raw.githubusercontent.com/"
        )

        url = url.replace(
            "/blob/",
            "/"
        )

    return url


def descargar_archivo(url, ruta_destino, descripcion):
    """
    Descarga un archivo desde GitHub.
    """

    url = convertir_url_github_a_raw(url)

    print()
    print(f"Descargando {descripcion}...")
    print(url)

    respuesta = requests.get(
        url,
        stream=True,
        timeout=180
    )

    if respuesta.status_code != 200:
        raise RuntimeError(
            f"No se pudo descargar {descripcion}.\n"
            f"Código HTTP: {respuesta.status_code}\n"
            f"URL: {url}"
        )

    tipo_contenido = respuesta.headers.get(
        "Content-Type",
        ""
    ).lower()

    if "text/html" in tipo_contenido:
        raise RuntimeError(
            f"La URL de {descripcion} devuelve una página HTML.\n"
            "Debes utilizar la URL RAW del archivo."
        )

    with open(ruta_destino, "wb") as archivo:

        for bloque in respuesta.iter_content(
            chunk_size=1024 * 1024
        ):
            if bloque:
                archivo.write(bloque)

    tamaño = os.path.getsize(
        ruta_destino
    )

    if tamaño == 0:
        raise RuntimeError(
            f"El archivo de {descripcion} está vacío."
        )

    print(
        f"Descarga completada: "
        f"{tamaño / (1024 * 1024):.2f} MB"
    )


def buscar_nombre_coordenada(dataset, nombres_posibles):
    """
    Busca una coordenada o dimensión entre varios nombres posibles.
    """

    for nombre in nombres_posibles:

        if nombre in dataset.coords or nombre in dataset.dims:
            return nombre

    return None


def normalizar_coordenadas(dataset, descripcion):
    """
    Normaliza latitud, longitud y tiempo.
    """

    nombre_lat = buscar_nombre_coordenada(
        dataset,
        [
            "lat",
            "latitude",
            "Latitude",
            "LATITUDE",
            "nav_lat",
            "y"
        ]
    )

    nombre_lon = buscar_nombre_coordenada(
        dataset,
        [
            "lon",
            "longitude",
            "Longitude",
            "LONGITUDE",
            "nav_lon",
            "x"
        ]
    )

    if nombre_lat is None:
        raise ValueError(
            f"No se encontró la latitud en {descripcion}.\n"
            f"Coordenadas: {list(dataset.coords)}"
        )

    if nombre_lon is None:
        raise ValueError(
            f"No se encontró la longitud en {descripcion}.\n"
            f"Coordenadas: {list(dataset.coords)}"
        )

    cambios = {}

    if nombre_lat != "lat":
        cambios[nombre_lat] = "lat"

    if nombre_lon != "lon":
        cambios[nombre_lon] = "lon"

    nombre_tiempo = buscar_nombre_coordenada(
        dataset,
        [
            "time",
            "date",
            "datetime",
            "TIME"
        ]
    )

    if nombre_tiempo is not None and nombre_tiempo != "time":
        cambios[nombre_tiempo] = "time"

    if cambios:
        dataset = dataset.rename(cambios)

    if dataset["lat"].ndim != 1 or dataset["lon"].ndim != 1:
        raise ValueError(
            f"{descripcion} utiliza una cuadrícula curvilínea.\n"
            "Este código requiere latitud y longitud 1D."
        )

    # Convertir longitudes 0-360 a -180-180.

    if float(dataset["lon"].max()) > 180:

        dataset = dataset.assign_coords(
            lon=((dataset["lon"] + 180) % 360) - 180
        )

    # Eliminar coordenadas repetidas.

    _, indices_lat = np.unique(
        dataset["lat"].values,
        return_index=True
    )

    _, indices_lon = np.unique(
        dataset["lon"].values,
        return_index=True
    )

    dataset = dataset.isel(
        lat=np.sort(indices_lat),
        lon=np.sort(indices_lon)
    )

    dataset = dataset.sortby("lat")
    dataset = dataset.sortby("lon")

    return dataset


def seleccionar_dimensiones_adicionales(
    variable,
    seleccion,
    descripcion
):
    """
    Selecciona dimensiones como depth, level o band.
    """

    for dimension, valor in seleccion.items():

        if dimension not in variable.dims:
            raise ValueError(
                f"La dimensión '{dimension}' no existe en "
                f"{descripcion}.\n"
                f"Dimensiones: {variable.dims}"
            )

        if isinstance(valor, int):

            variable = variable.isel({
                dimension: valor
            })

        else:

            variable = variable.sel(
                {
                    dimension: valor
                },
                method="nearest"
            )

    # Eliminar dimensiones unitarias.

    dimensiones_unitarias = [
        dimension
        for dimension, tamaño in variable.sizes.items()
        if tamaño == 1
        and dimension not in ["time", "lat", "lon"]
    ]

    if dimensiones_unitarias:

        variable = variable.squeeze(
            dim=dimensiones_unitarias,
            drop=True
        )

    dimensiones_adicionales = [
        dimension
        for dimension in variable.dims
        if dimension not in ["time", "lat", "lon"]
    ]

    if dimensiones_adicionales:
        raise ValueError(
            f"La variable {descripcion} todavía contiene "
            f"dimensiones adicionales: {dimensiones_adicionales}.\n"
            "Añade su selección en el campo 'nivel'."
        )

    return variable


def calcular_resolucion(coordenada):
    """
    Calcula la separación mediana entre coordenadas.
    """

    valores = np.asarray(
        coordenada.values,
        dtype=float
    )

    diferencias = np.abs(
        np.diff(valores)
    )

    diferencias = diferencias[
        np.isfinite(diferencias)
        & (diferencias > 0)
    ]

    if len(diferencias) == 0:
        return np.nan

    return float(
        np.median(diferencias)
    )


def normalizar_tiempo_mensual(variable):
    """
    Convierte la dimensión temporal a una fecha por año y mes.

    Si existen varias mediciones en el mismo mes,
    calcula la media mensual.
    """

    if "time" not in variable.dims:
        return variable

    fechas = pd.to_datetime(
        variable["time"].values
    )

    fechas_mensuales = (
        fechas
        .to_period("M")
        .to_timestamp()
    )

    variable = variable.assign_coords(
        time=fechas_mensuales
    )

    if variable.indexes["time"].duplicated().any():

        variable = variable.groupby(
            "time"
        ).mean(
            dim="time",
            skipna=True
        )

    return variable.sortby("time")


def indices_mas_cercanos(valores_ordenados, valores_busqueda):
    """
    Obtiene el índice de la coordenada más próxima.
    """

    valores_ordenados = np.asarray(
        valores_ordenados,
        dtype=float
    )

    valores_busqueda = np.asarray(
        valores_busqueda,
        dtype=float
    )

    if len(valores_ordenados) == 1:

        return np.zeros(
            len(valores_busqueda),
            dtype=int
        )

    posiciones = np.searchsorted(
        valores_ordenados,
        valores_busqueda
    )

    posiciones = np.clip(
        posiciones,
        1,
        len(valores_ordenados) - 1
    )

    izquierda = valores_ordenados[
        posiciones - 1
    ]

    derecha = valores_ordenados[
        posiciones
    ]

    elegir_derecha = (
        np.abs(derecha - valores_busqueda)
        <
        np.abs(valores_busqueda - izquierda)
    )

    return (
        posiciones - 1
        + elegir_derecha.astype(int)
    )


def convertir_tipo_json(valor):
    """
    Convierte valores de pandas y NumPy a tipos JSON.
    """

    if valor is None:
        return None

    if isinstance(valor, np.integer):
        return int(valor)

    if isinstance(valor, np.floating):

        if not np.isfinite(valor):
            return None

        return float(valor)

    if isinstance(valor, np.bool_):
        return bool(valor)

    if isinstance(valor, pd.Timestamp):
        return valor.isoformat()

    if pd.isna(valor):
        return None

    return valor


